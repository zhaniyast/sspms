def _clean(w): return w.rstrip("2")

def _surname(stem, male, rng):
    stem = _clean(stem); style = rng.random()
    if style < 0.45:                      # казахская форма: Ахмет ұлы / қызы -> одним словом
        return stem + ("ұлы" if male else "қызы")
    last = stem[-1].lower()
    if last in "аәеиоөұүыіу":
        suf = "в" if male else "ва"
    else:
        suf = "ов" if male else "ова"
    return stem + suf

class NameGen:
    """Полное имя не повторяется никогда; имена стараемся раздавать уникально."""
    def __init__(self, seed=42, kazakh_share=0.95):
        self.rng = random.Random(seed); self.share = kazakh_share
        self.m = [_clean(x) for x in MALE]; self.f = [_clean(x) for x in FEMALE]
        self.rng.shuffle(self.m); self.rng.shuffle(self.f)
        self.other = OTHER[:]; self.rng.shuffle(self.other)
        self.used_full = set(); self.used_first = set()

    def _first(self, pool, male):
        for n in pool:
            if n not in self.used_first:
                return n
        return self.rng.choice(pool)       # пул закончился, повтор имени допустим

    def make(self):
        male = self.rng.random() < 0.5
        for _ in range(1000):
            if self.rng.random() < self.share:
                first = self._first(self.m if male else self.f, male)
                last = _surname(self.rng.choice(SURN), male, self.rng)
                kz = True
            else:
                first, last = self.rng.choice(self.other)
                kz = False
            if (first, last) not in self.used_full:
                self.used_full.add((first, last)); self.used_first.add(first)
                return {"first_name": first, "last_name": last, "male": male, "kazakh": kz}
        raise RuntimeError("не удалось подобрать уникальное имя")
